#!/usr/bin/env node
/**
 * build-text-paths — pre-renders phrases from registry.json into SVG path
 * data using opentype.js, outputs src/lib/text-paths/generated.ts.
 *
 * Why build-time, not runtime: opentype.js is ~80KB minified+gzipped.
 * Shipping it to every page just so a Burst can spell "WELCOME" once is
 * overkill — most use cases want a known phrase rendered at build, then
 * referenced by key at runtime (zero JS cost). Mirrors the pattern of
 * scripts/build-gradients.mjs.
 *
 * Run: npm run build:text-paths
 */

import opentype from 'opentype.js';
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');

const registryPath = path.join(projectRoot, 'src/lib/text-paths/registry.json');
const outputPath = path.join(projectRoot, 'src/lib/text-paths/generated.ts');

if (!fs.existsSync(registryPath)) {
  console.error(`[text-paths] registry not found at ${registryPath}`);
  process.exit(1);
}

const registry = JSON.parse(fs.readFileSync(registryPath, 'utf-8'));

// Pre-load every font referenced in the registry. opentype.loadSync is
// deprecated as of v1.4 — use parse(buffer) directly.
const fontCache = {};
for (const [key, fontPath] of Object.entries(registry.fonts || {})) {
  const absPath = path.join(projectRoot, fontPath);
  if (!fs.existsSync(absPath)) {
    console.warn(`[text-paths] font "${key}" not found at ${absPath} — skipping any phrases that reference it`);
    continue;
  }
  try {
    const buffer = fs.readFileSync(absPath);
    // opentype.parse takes an ArrayBuffer; Node Buffer.buffer gives the
    // underlying AB but might include unrelated bytes — slice to be safe.
    const ab = buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength);
    fontCache[key] = opentype.parse(ab);
  } catch (err) {
    console.warn(`[text-paths] failed to load font "${key}":`, err.message);
  }
}

// Generate SVG path data per character (not one combined path) so each
// strand can trace one letter and get its own palette colour. Spaces are
// skipped but their advance width still pushes the cursor forward, so
// inter-letter gaps stay correct. The downstream consumer (Burst's
// tracePath: 'phrase:KEY' shorthand) gets an array, distributes one
// strand per letter via s % paths.length, and the auto-strands logic
// sets strand count = letter count when palette is in play.
const generated = {};
const meta = {};
for (const phrase of registry.phrases || []) {
  const font = fontCache[phrase.font];
  if (!font) {
    console.warn(`[text-paths] phrase "${phrase.key}" requires font "${phrase.font}" — not loaded, skipping`);
    continue;
  }
  const paths = [];
  // Track union bbox across all glyph paths so we can emit a viewBox.
  // Glyph y values are negative-up in opentype space (baseline at 0,
  // ascenders go negative). We carry the raw coords through to the
  // viewBox — consumers render with the same coord system the path
  // data uses, no flip required.
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  let x = 0;
  const sizeScale = phrase.size / font.unitsPerEm;
  for (const ch of phrase.text) {
    const glyph = font.charToGlyph(ch);
    const advance = (glyph.advanceWidth || 0) * sizeScale;
    if (ch !== ' ') {
      const cp = glyph.getPath(x, 0, phrase.size);
      paths.push(cp.toPathData(2));
      const bb = cp.getBoundingBox();
      if (bb.x1 < minX) minX = bb.x1;
      if (bb.y1 < minY) minY = bb.y1;
      if (bb.x2 > maxX) maxX = bb.x2;
      if (bb.y2 > maxY) maxY = bb.y2;
    }
    x += advance;
  }
  generated[phrase.key] = paths;
  // Pad the viewBox slightly so strokes don't clip at the edges. The
  // padding amount scales with phrase size — bigger phrases get more.
  const pad = phrase.size * 0.1;
  const vbX = (minX - pad).toFixed(2);
  const vbY = (minY - pad).toFixed(2);
  const vbW = (maxX - minX + pad * 2).toFixed(2);
  const vbH = (maxY - minY + pad * 2).toFixed(2);
  // Raw bbox dimensions (before padding) — consumers use these to
  // pick a runtime layout (e.g. fit-in-column vs full-width-centred)
  // based on the phrase's natural aspect ratio.
  const naturalW = +(maxX - minX).toFixed(2);
  const naturalH = +(maxY - minY).toFixed(2);
  meta[phrase.key] = {
    paths,
    viewBox: `${vbX} ${vbY} ${vbW} ${vbH}`,
    width: naturalW,
    height: naturalH,
  };
}

const content = `// Generated by scripts/build-text-paths.mjs — do not edit by hand.
// Run \`npm run build:text-paths\` to regenerate.
//
// TEXT_PATHS: per-character SVG path data arrays. Burst's tracePath:
// "phrase:KEY" reads this directly — one strand per letter, palette
// colour distributed across the word.
//
// TEXT_PATHS_META: same paths plus a computed viewBox covering the
// union bbox of all glyphs. Shape's phraseKey reads this so the
// rendered SVG fits the typography without runtime bbox math.

export interface PhraseMeta {
  paths: string[];
  viewBox: string;
  /** Natural bbox width in path units (no padding) — use to compute
   *  rendered width when targeting a fixed letter height. */
  width: number;
  /** Natural bbox height in path units (no padding). */
  height: number;
}

export const TEXT_PATHS: Record<string, string[]> = ${JSON.stringify(generated, null, 2)};

export const TEXT_PATHS_META: Record<string, PhraseMeta> = ${JSON.stringify(meta, null, 2)};
`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, content);

const phraseList = Object.keys(generated).join(', ');
console.log(`[text-paths] generated ${Object.keys(generated).length} phrases (${phraseList}) → ${path.relative(projectRoot, outputPath)}`);
